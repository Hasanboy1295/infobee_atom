CREATE TABLE atom_predictions (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    atom_request_id     BIGINT         NOT NULL,
    created_by          BIGINT         NOT NULL,
    status              VARCHAR(32)    NOT NULL DEFAULT 'INPUT_READY',
    input_conditions    TEXT           NOT NULL,
    input_filename      VARCHAR(300),
    input_content_type  VARCHAR(100),
    result_data         TEXT,
    result_filename     VARCHAR(300),
    result_content_type VARCHAR(100),
    model_version       VARCHAR(100),
    execution_time_ms   BIGINT,
    error_message       TEXT,
    created_at          TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_pred_atom FOREIGN KEY (atom_request_id) REFERENCES atom_requests(id),
    CONSTRAINT fk_pred_user FOREIGN KEY (created_by)      REFERENCES users(id)
);
