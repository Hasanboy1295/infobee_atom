CREATE TABLE substance_infos (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cpsr_request_id         BIGINT       NOT NULL,
    substance_name          VARCHAR(300) NOT NULL,
    cas_number              VARCHAR(30),
    ec_number               VARCHAR(30),
    molecular_formula       VARCHAR(100),
    molecular_weight        DOUBLE PRECISION,
    purity                  VARCHAR(100),
    intended_use            TEXT,
    intended_concentration  DOUBLE PRECISION,
    product_type            VARCHAR(100),
    target_population       VARCHAR(100),
    remarks                 TEXT,
    created_at              TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at              TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_substance_cpsr FOREIGN KEY (cpsr_request_id) REFERENCES cpsr_requests(id)
);

CREATE TABLE toxicity_records (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    substance_name  VARCHAR(300) NOT NULL,
    cas_number      VARCHAR(30),
    ec_number       VARCHAR(30),
    source_db       VARCHAR(50)  NOT NULL,
    source_id       VARCHAR(100),
    endpoint_name   VARCHAR(200) NOT NULL,
    endpoint_value  TEXT,
    endpoint_unit   VARCHAR(50),
    test_guideline  VARCHAR(200),
    test_method     VARCHAR(200),
    remarks         TEXT,
    created_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE cpsr_evaluations (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cpsr_request_id     BIGINT         NOT NULL,
    evaluator_id        BIGINT,
    status              VARCHAR(32)    NOT NULL DEFAULT 'PENDING',
    sed_value           DOUBLE PRECISION,
    sed_unit            VARCHAR(50),
    mos_value           DOUBLE PRECISION,
    noael_value         DOUBLE PRECISION,
    noael_unit          VARCHAR(50),
    risk_assessment     TEXT,
    conclusion          TEXT,
    evaluator_opinion   TEXT,
    remarks             TEXT,
    created_at          TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_eval_cpsr    FOREIGN KEY (cpsr_request_id) REFERENCES cpsr_requests(id),
    CONSTRAINT fk_eval_user    FOREIGN KEY (evaluator_id)    REFERENCES users(id)
);

CREATE TABLE llm_inferences (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cpsr_request_id     BIGINT         NOT NULL,
    model_name          VARCHAR(200)   NOT NULL,
    inference_type      VARCHAR(32)    NOT NULL,
    prompt              TEXT           NOT NULL,
    response_text       TEXT,
    reference_sources   TEXT,
    tokens_used         INTEGER,
    latency_ms          BIGINT,
    status              VARCHAR(16)    NOT NULL DEFAULT 'PENDING',
    error_message       TEXT,
    created_at          TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_llm_cpsr FOREIGN KEY (cpsr_request_id) REFERENCES cpsr_requests(id)
);
